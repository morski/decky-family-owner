import { afterEach, expect, it, vi } from "vitest";
import { act, cleanup, render } from "@testing-library/react";
import { ConnectedOwnerBadge } from "../src/components/ConnectedOwnerBadge";
import { Lifecycle } from "../src/services/lifecycle";
import { VisibleApps } from "../src/services/visibleApps";
import { OwnersService } from "../src/services/ownersService";
import { PersonaService } from "../src/services/personaService";
import { SettingsStore } from "../src/settings/settings";
import { accountIdToSteamId64 } from "../src/utils/steamId";
afterEach(() => { cleanup(); vi.useRealTimers(); });
it("connected badges refresh selected owner, hide on account transition/disable/unload, cancel stale persona", async () => {
  let owner = 2;
  const ownership = new OwnersService({ resolve: async appId => [{ appid: appId, steamid: accountIdToSteamId64(owner) }] });
  ownership.setCurrentUser({ accountId: 1, steamId64: accountIdToSteamId64(1)! });
  let finish!: (value: { name: string }) => void;
  const personas = new PersonaService({ resolve: () => new Promise(resolve => { finish = resolve; }), isAllowedAvatarUrl: () => false });
  personas.setCurrentAccount(1);
  const lifecycle = new Lifecycle(); const settings = new SettingsStore();
  const visible = new VisibleApps(() => ownership.refresh());
  const services = { ownership, personas, lifecycle, settings, visible };
  const { container, getByRole } = render(<ConnectedOwnerBadge appId={10} services={services} />);
  await act(async () => {});
  expect(getByRole("img").getAttribute("aria-label")).toContain("Steam Family member");
  const stale = finish;
  await act(async () => { owner = 3; ownership.refresh(); });
  await act(async () => { stale({ name: "Old lender" }); });
  expect(getByRole("img").getAttribute("aria-label")).not.toContain("Old lender");
  act(() => { personas.setCurrentAccount(undefined); ownership.setCurrentUser(undefined); });
  expect(container.childElementCount).toBe(0);
  act(() => settings.update({ enabled: false })); expect(container.childElementCount).toBe(0);
  act(() => lifecycle.dispose()); expect(container.childElementCount).toBe(0);
  visible.dispose(); ownership.dispose(); personas.dispose(); settings.dispose();
});
it("uses one timer for visible apps and releases it after final unmount", () => {
  vi.useFakeTimers(); const refresh = vi.fn(); const visible = new VisibleApps(refresh);
  const a = visible.watch(10), b = visible.watch(10), c = visible.watch(20);
  expect(vi.getTimerCount()).toBe(1);
  vi.advanceTimersByTime(30000); expect(refresh).toHaveBeenCalledTimes(1);
  a(); a(); b(); expect(vi.getTimerCount()).toBe(1); c(); expect(vi.getTimerCount()).toBe(0);
  visible.watch(10); visible.dispose(); expect(vi.getTimerCount()).toBe(0);
});
